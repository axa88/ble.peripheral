"""Generate or verify the single embedded browser asset using only stdlib."""
import argparse
import gzip
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
source = root / "web/index.html"
output = root / "src/webAssets.cpp"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="Decompress the current array and compare with HTML")
args = parser.parse_args()
html = source.read_bytes()
if args.check:
    text = output.read_text(encoding="utf-8")
    array = text.split("indexGzip[] = {", 1)[1].split("};", 1)[0]
    packed = bytes(int(value, 16) for value in re.findall(r"0x([0-9a-fA-F]{2})", array))
    if gzip.decompress(packed) != html:
        raise SystemExit("Embedded HTML differs from web/index.html; regenerate the asset")
    if packed[4:8] != bytes(4):
        raise SystemExit("Expected deterministic zero gzip mtime")
    print(f"Embedded asset verified: {len(packed)} gzip bytes -> {len(html)} HTML bytes")
else:
    packed = gzip.compress(html, compresslevel=9, mtime=0)
    lines = ["// Generated by tools/generate-web-assets.py; do not edit the byte array.",
             '#include "bleConfig.h"', "#if BLE_ENABLE_WEB_INTERFACE", '#include "webAssets.h"',
             "namespace WebAssets", "{", "const uint8_t indexGzip[] = {"]
    lines += ["    " + ", ".join(f"0x{v:02x}" for v in packed[i:i + 16]) + "," for i in range(0, len(packed), 16)]
    lines += ["};", "const size_t indexGzipSize = sizeof(indexGzip);", "}", "#endif", ""]
    output.write_bytes("\r\n".join(lines).encode("utf-8"))
    print(f"Generated {len(packed)} gzip bytes from {len(html)} HTML bytes")
